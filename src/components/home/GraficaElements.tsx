/**
 * MiniWave
 * Decorative gentle wave used in countdown boxes and underlines.
 */
export const MiniWave: React.FC<{
  className?: string;
  color?: string;
  strokeWidth?: number;
  lgStrokeWidth?: number;
  preserveAspectRatio?: string;
}> = ({
  className = "",
  color = "#ffffff",
  strokeWidth = 2,
  lgStrokeWidth,
  preserveAspectRatio,
}) => {
  return (
    <svg
      viewBox="0 0 60 12"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={`inline-block ${className}`}
      style={
        {
          "--wave-stroke": `${strokeWidth}`,
          ...(lgStrokeWidth ? { "--wave-stroke-lg": `${lgStrokeWidth}` } : {}),
        } as React.CSSProperties
      }
      preserveAspectRatio={preserveAspectRatio}
      aria-hidden="true"
    >
      <path
        d="M2 6C10 2 18 10 26 6C34 2 42 10 50 6C54 4 57 4 58 6"
        stroke={color}
        strokeLinecap="round"
        className={
          lgStrokeWidth
            ? "[stroke-width:var(--wave-stroke)] lg:[stroke-width:var(--wave-stroke-lg)]"
            : undefined
        }
        strokeWidth={lgStrokeWidth ? undefined : strokeWidth}
      />
    </svg>
  );
};

/**
 * TimelineTargetNode
 * The concentric circle milestone node from grafica.svg.
 */
export const TimelineTargetNode: React.FC<{
  variant?: "sage" | "burgundy";
  size?: number;
}> = ({ variant = "sage", size = 24 }) => {
  const isSage = variant === "sage";
  return (
    <div
      style={{ width: size, height: size }}
      className={`rounded-full flex items-center justify-center shrink-0 border-2 shadow-xs ${
        isSage
          ? "bg-[#e5edd8] border-[#667b4e]"
          : "bg-[#fde7e2] border-[#4a151d]"
      }`}
    >
      <div
        className={`w-2 h-2 rounded-full ${
          isSage ? "bg-[#667b4e]" : "bg-[#4a151d]"
        }`}
      />
    </div>
  );
};

